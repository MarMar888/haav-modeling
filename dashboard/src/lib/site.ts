// One place for what search engines and AI crawlers are told about the site: the canonical origin, the description,
// the per-page metadata helper, and the plain-text summaries served at /llms.txt and /llms-full.txt.
import type { Metadata } from "next";

export const SITE_URL = "https://haav.build";
export const SITE_NAME = "Haav";
export const SITE_TITLE = "Haav | Highly Amphibious / Autonomous Vessel";
export const SITE_DESCRIPTION =
  "Haav (Highly Amphibious / Autonomous Vessel) is a student team building a 4-foot autonomous boat from the ground up, with every decision modeled before it is built.";
export const CONTACT_EMAIL = "mhbarrett@wisc.edu";

// Pages worth indexing. The workshop (/bom, /optimization), /handout and /api are working tools and stay out.
export const PUBLIC_PATHS = [
  { path: "/", title: "Home", description: "What Haav is, the boat, the build timeline, the team and how to sponsor." },
  { path: "/simulation", title: "Simulation", description: "Simulation studies for the boat: propeller, thrust, motor drive and speed." },
  { path: "/join", title: "Become a member", description: "How UW-Madison students can join the build team." },
] as const;

// Generated by src/app/opengraph-image.tsx.
const SHARE_IMAGE = { url: "/opengraph-image", width: 1200, height: 630, alt: "Haav: Highly Amphibious / Autonomous Vessel" };

// Canonical URL, Open Graph and Twitter tags for one page. Child metadata replaces the layout's openGraph and twitter
// objects rather than merging, so every page states its own.
export function pageMetadata({ title, description, path }: { title?: string; description: string; path: string }): Metadata {
  const full = title ? `${title} | ${SITE_NAME}` : SITE_TITLE;
  return {
    ...(title && { title }),
    description,
    alternates: { canonical: path },
    openGraph: { type: "website", siteName: SITE_NAME, locale: "en_US", title: full, description, url: path, images: [SHARE_IMAGE] },
    twitter: { card: "summary_large_image", title: full, description, images: [SHARE_IMAGE.url] },
  };
}

export function absoluteUrl(path: string) {
  return new URL(path, SITE_URL).toString();
}
